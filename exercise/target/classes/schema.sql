CREATE TABLE LIBRO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(255),
    FECHA_INGRESO TIMESTAMP,
    ACTIVO BOOLEAN,
    AUTOR VARCHAR(255),
    EDITORIAL VARCHAR(255),
    ANIO INT
);

CREATE TABLE PERIODICO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(255),
    FECHA_INGRESO TIMESTAMP,
    ACTIVO BOOLEAN,
    EDITORIAL VARCHAR(255),
    FECHA_PUBLICACION DATE
);

CREATE TABLE COMPUTADOR (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(255),
    FECHA_INGRESO TIMESTAMP,
    ACTIVO BOOLEAN,
    MARCA VARCHAR(255),
    MODELO VARCHAR(255),
    SISTEMA_OPERATIVO VARCHAR(255),
    TIPO VARCHAR(20)
);